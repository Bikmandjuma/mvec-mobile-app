  /// Builds a category map following the backend schema.
  Map<String, dynamic> _category(int id, String name, String slug) =>
      <String, dynamic>{
        'id': id,
        'name': name,
        'slug': slug,
        'productCount': 100 + id * 37,
        'icon': 'https://picsum.photos/seed/cat-$slug/200',
        'media': {
          'mainImage': 'https://picsum.photos/seed/cat-$slug/200',
        },
      };

  /// Builds a vendor map following the backend schema.
  Map<String, dynamic> _vendor(
    int id,
    String name,
    String description, {
    required double rating,
    required int reviewCount,
    required int productCount,
    required bool isVerified,
    required bool isFeatured,
  }) =>
      <String, dynamic>{
        'id': id,
        'name': name,
        'slug': name.toLowerCase(),
        'description': description,
        'rating': rating,
        'reviewCount': reviewCount,
        'productCount': productCount,
        'isVerified': isVerified,
        'isFeatured': isFeatured,
        'media': {
          'logo': 'https://picsum.photos/seed/logo-$id/200',
          'banner': 'https://picsum.photos/seed/banner-$id/720/200',
        },
      };

  /// Builds a product map following the backend schema
  /// (`media.mainImage`, `stockQuantity`, `brand`, `slug`, ...).
  Map<String, dynamic> _product(
    int id,
    String name,
    String slug,
    String brand, {
    required double price,
    double? originalPrice,
    required int stockQuantity,
    required double rating,
    required int ratingCount,
    required List<String> badges,
    required int categoryId,
    required String categoryName,
    required int vendorId,
    required String vendorName,
  }) =>
      <String, dynamic>{
        'id': id,
        'name': name,
        'slug': slug,
        'description': 'High-quality $name from $vendorName.',
        'brand': brand,
        'price': price,
        'originalPrice': originalPrice,
        'stockQuantity': stockQuantity,
        'rating': rating,
        'ratingCount': ratingCount,
        'badges': badges,
        'isFeatured': false,
        'isOnSale': originalPrice != null,
        'category': <String, dynamic>{
          'id': categoryId,
          'name': categoryName,
          'slug': categoryName.toLowerCase().replaceAll(' ', '-'),
        },
        'vendor': <String, dynamic>{
          'id': vendorId,
          'name': vendorName,
          'media': {'logo': 'https://picsum.photos/seed/logo-$id/200'},
        },
        'media': <String, dynamic>{
          'mainImage': 'https://picsum.photos/seed/product-$id/400',
        },
      };
